#!/usr/bin/env python3
"""Generate the resolution-sweep and weighted-BCE ablation configs.

    python scripts/make_ablation_configs.py            # dry run: show, verify, write nothing
    python scripts/make_ablation_configs.py --write

Every config is DERIVED from the corresponding corrected phase-2 config in this
tree, never hand-written. Then it is checked: resolved through TrainConfig, it
must differ from its source in exactly the field the ablation is about, and
nothing else. An ablation that also changes something else is not an ablation.

Resolution sweep
    The core grid ran each model at its own native resolution (verify with the
    input_size in any run_manifest.json):
        RETFound-DINOv2 518 . DINOv2-L 504 . RETFound-MAE 224 . DINOv3-L 224
        ConvNeXtV2-B 224 . EfficientNet-B2 260
    so architecture and resolution are confounded across the grid. These configs
    vary resolution WITHIN one model, everything else held fixed -- including
    batch size, so a memory-driven batch change cannot masquerade as an effect.

        dinov2_large_res224   DINOv2-L at 224   (native 504; one ViT going down)
        dinov2_large_res336   DINOv2-L at 336   (midpoint)
        convnextv2_res448     ConvNeXtV2-B at 448 (native 224; one CNN going up)

    Each has its own output_dir subdirectory: the two DINOv2-L points share
    architecture "dinov2" and would otherwise resolve to the same run_dir.

Weighted-BCE ablation
    The retrain switched use_weighted_bce off, and hypertension ECE fell from
    0.16-0.22 to 0.029. But much else changed in the retrain too. This arm turns
    the weighted loss back on for EfficientNet-B2 and changes nothing else, so
    the calibration claim can be attributed to the loss rather than asserted.

        efficientnet_b2_wbce  EfficientNet-B2 with use_weighted_bce: true
"""
from __future__ import annotations

import argparse
import dataclasses
import difflib
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.config.schema import TrainConfig  # noqa: E402
from apply_isbi_config_edits import set_model_kwarg, set_scalar  # noqa: E402

TASKS = ("cimt", "hypertension")

# (new name, source stem, scalar edits, model_kwargs edits)
ARMS: dict[str, list[tuple[str, str, dict[str, str], dict[str, str]]]] = {
    "resolution": [
        ("dinov2_large_res224", "dinov2_large", {}, {"input_size_override": "224"}),
        ("dinov2_large_res336", "dinov2_large", {}, {"input_size_override": "336"}),
        ("convnextv2_res448", "convnextv2", {}, {"input_size_override": "448"}),
    ],
    "wbce": [
        ("efficientnet_b2_wbce", "efficientnet_b2",
         {"use_weighted_bce": "true", "pos_weight": "null"}, {}),
    ],
}
OUT_BASE = {"resolution": "outputs_isbi_res", "wbce": "outputs_isbi_wbce"}

# fields each arm is ALLOWED to change; anything else differing is an error
ALLOWED = {
    "resolution": {"output_dir", "model_kwargs"},
    "wbce": {"output_dir", "use_weighted_bce", "pos_weight"},
}
ALLOWED_KWARGS = {"resolution": {"input_size_override"}, "wbce": set()}

# patch / stride constraints, so a typo cannot launch a run that crashes at step 0
STRIDE = {"dinov2": 14, "convnextv2": 32}

ERRORS: list[str] = []


def resolve(text: str) -> TrainConfig:
    raw = yaml.safe_load(text) or {}
    raw.update(fold=0, seed=42)
    cfg = TrainConfig.from_dict(raw)
    cfg.validate()
    return cfg


def header(arm: str, name: str, src: Path, scal: dict, kw: dict) -> str:
    changed = ", ".join([f"{k}: {v}" for k, v in scal.items()] +
                        [f"model_kwargs.{k}: {v}" for k, v in kw.items()])
    return (
        f"# {name}\n"
        f"#\n"
        f"# GENERATED by scripts/make_ablation_configs.py -- do not edit by hand.\n"
        f"# Source: {src.relative_to(ROOT).as_posix()}\n"
        f"# Arm:    {arm}\n"
        f"# Change: {changed}\n"
        f"#\n"
        f"# Identical to the source in every other field, which the generator verifies\n"
        f"# through TrainConfig before writing. Edit the source and regenerate instead.\n"
        f"#\n"
    )


def build(arm: str, task: str, name: str, stem: str,
          scal: dict, kw: dict) -> tuple[Path, str | None, str]:
    src = ROOT / f"tasks/{task}/configs/phase2/{stem}_phase2.yaml"
    dst = ROOT / f"tasks/{task}/configs/{arm}/{name}.yaml"
    tag = f"{task}/{name}"
    if not src.exists():
        ERRORS.append(f"[{tag}] source config missing: {src.relative_to(ROOT)}")
        return dst, None, ""
    original = src.read_text()
    base = resolve(original)

    # Refuse to derive from an uncorrected source. On a tree where
    # apply_isbi_config_edits.py was never run, every generated config would
    # inherit the pre-dedup CSV and the weighted loss.
    if base.use_weighted_bce:
        ERRORS.append(f"[{tag}] source has use_weighted_bce=true -- run "
                      f"scripts/apply_isbi_config_edits.py --write first")
    if task == "hypertension" and not base.labels_csv.endswith("_dedup.csv"):
        ERRORS.append(f"[{tag}] source labels_csv is not the dedup CSV -- run "
                      f"scripts/apply_isbi_config_edits.py --write first")

    body = re.sub(r"\A(#[^\n]*\n)+", "", original)  # drop the source's header
    lines = body.splitlines()
    out_dir = (f"{OUT_BASE[arm]}/{name}" if arm == "resolution" else OUT_BASE[arm])
    lines, _ = set_scalar(lines, "output_dir", out_dir)
    for k, v in scal.items():
        lines, _ = set_scalar(lines, k, v)
    for k, v in kw.items():
        lines, _ = set_model_kwarg(lines, k, v)
    text = header(arm, name, src, scal, kw) + "\n".join(lines) + "\n"

    # ---- verify: only the intended fields may differ -------------------------
    new = resolve(text)
    diffs = [f.name for f in dataclasses.fields(TrainConfig)
             if getattr(new, f.name) != getattr(base, f.name)]
    bad = [d for d in diffs if d not in ALLOWED[arm]]
    if bad:
        ERRORS.append(f"[{tag}] differs from its source in {bad} -- not an ablation")
    if "model_kwargs" in diffs:
        a, b = base.model_kwargs or {}, new.model_kwargs or {}
        kdiff = {k for k in set(a) | set(b) if a.get(k) != b.get(k)}
        stray = kdiff - ALLOWED_KWARGS[arm]
        if stray:
            ERRORS.append(f"[{tag}] model_kwargs also changed {sorted(stray)}")
    for k, v in kw.items():
        if (new.model_kwargs or {}).get(k) != int(v):
            ERRORS.append(f"[{tag}] model_kwargs.{k} did not land (got "
                          f"{(new.model_kwargs or {}).get(k)!r})")
    if "input_size_override" in kw:
        stride = STRIDE.get(new.architecture)
        size = int(kw["input_size_override"])
        if stride and size % stride:
            ERRORS.append(f"[{tag}] {size} is not a multiple of {stride} "
                          f"for {new.architecture}")
    for k, v in scal.items():
        got = getattr(new, k)
        want = None if v == "null" else (v == "true" if v in ("true", "false") else v)
        if got != want:
            ERRORS.append(f"[{tag}] {k} did not land (got {got!r}, wanted {want!r})")

    return dst, text, original


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--quiet", action="store_true", help="no diffs, summary only")
    args = ap.parse_args()

    produced: list[tuple[Path, str]] = []
    for arm, specs in ARMS.items():
        for task in TASKS:
            for name, stem, scal, kw in specs:
                dst, text, original = build(arm, task, name, stem, scal, kw)
                if text is None:
                    continue
                produced.append((dst, text))
                rel = dst.relative_to(ROOT).as_posix()
                state = ("unchanged" if dst.exists() and dst.read_text() == text
                         else "update" if dst.exists() else "new")
                print(f"  {state:<9} {rel}")
                if not args.quiet and state != "unchanged":
                    src_body = re.sub(r"\A(#[^\n]*\n)+", "", original)
                    new_body = re.sub(r"\A(#[^\n]*\n)+", "", text)
                    d = "".join(difflib.unified_diff(
                        src_body.splitlines(keepends=True),
                        new_body.splitlines(keepends=True),
                        fromfile=f"phase2/{name.split('_res')[0].split('_wbce')[0]}",
                        tofile=rel, n=0))
                    print("".join("      " + l for l in d.splitlines(keepends=True)))

    # ---- run_dir uniqueness across EVERY config in the tree --------------------
    owners: dict[str, list[str]] = {}
    pool = [(p, p.read_text()) for p in sorted(ROOT.glob("tasks/*/configs/phase2/*.yaml"))]
    pool += [(p, p.read_text()) for p in sorted(ROOT.glob("tasks/*/configs/vessel/*.yaml"))
             if "multimodal" not in p.name]
    pool += produced
    for p, text in pool:
        try:
            rd = str(resolve(text).run_dir)
        except Exception as exc:  # noqa: BLE001
            ERRORS.append(f"[{p.name}] does not resolve: {exc}")
            continue
        owners.setdefault(rd, []).append(p.relative_to(ROOT).as_posix())
    for rd, who in owners.items():
        if len(who) > 1:
            ERRORS.append(f"run_dir collision {rd}: {who}")
    print(f"\n  {len(owners)} distinct run_dirs across {len(pool)} configs "
          f"(core + vessel + generated)")

    for e in ERRORS:
        print(f"  ERROR  {e}")
    if ERRORS:
        print(f"\n{len(ERRORS)} errors -- nothing written.")
        return 1

    if not args.write:
        print(f"\n{len(produced)} configs verified. Dry run -- rerun with --write.")
        return 0
    for dst, text in produced:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
    print(f"\n{len(produced)} configs verified and written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
