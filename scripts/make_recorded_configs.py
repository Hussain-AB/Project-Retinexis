#!/usr/bin/env python3
"""Generate the "recorded" arm: ConvNeXtV2-B and EfficientNet-B2 retrained on
BRSET images that HAVE a clinical record, so the missing-record / camera
shortcut cannot be learned.

    python scripts/make_recorded_configs.py --brset-labels ~/labels_brset.csv            # dry run
    python scripts/make_recorded_configs.py --brset-labels ~/labels_brset.csv --write

Why
---
The BRSET hypertension label is 1 when 'comorbidities' mentions hypertension and
0 otherwise, INCLUDING when the field is empty (no record). About half of BRSET
has no record and almost all Nikon NF5050 images are in that half, so camera
and cohort predict the label (scripts/isbi_label_audit.py). Re-scoring the
existing models on record-present images is not the same as training without
the shortcut. This arm trains on record-present BRSET only and is tested on
exactly the images the label audit calls "BRSET, record present".

What it writes (only with --write; dry run writes nothing)
-----------------------------------------------------------
  <dedup CSV dir>/combined_metadata_dedup_brset_recorded.csv
      the rows of the dedup CSV whose image is BRSET, Adequate, with a record.
      Row text is copied unchanged (read and written as strings).
  tasks/hypertension/splits/hypertension_combined_5fold_splits_brset_recorded.json
      the existing 5-fold splits with every non-kept image removed from every
      id list. Same patients in the same folds; nothing is re-split.
  ..._brset_recorded.provenance.json
      sha256 of every input and output, per-fold counts.
  tasks/hypertension/configs/recorded/{convnextv2,efficientnet_b2}_recorded.yaml
      the phase-2 config with labels_csv, splits_file and output_dir changed
      and nothing else (verified through TrainConfig).

Checks -- any failure writes nothing
------------------------------------
  * the source phase-2 configs are the corrected ones (dedup CSV, no wBCE),
  * every BRSET row of the dedup CSV is an Adequate image in labels_brset.csv,
    and the label rebuilt from 'comorbidities' equals the CSV label for every
    BRSET row (proves it is the file the labels were built from),
  * the splits JSON has the expected shape; image-id lists are recognised by
    content and the outer test list by matching the core runs' test predictions,
  * after filtering: each fold's id lists are disjoint, no patient straddles
    the test list and the other lists, every kept image is in exactly one test
    fold, and each fold's test list equals the core ConvNeXtV2-B and
    EfficientNet-B2 runs' record-present BRSET test images -- so new and old
    models are compared on identical images,
  * kept images = --expect-images (7,350 = Adequate BRSET with a record),
  * the generated configs differ from their source only in the three fields,
    and no run_dir collides with any other config in the tree.
"""
from __future__ import annotations

import argparse
import dataclasses
import difflib
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.config.schema import TrainConfig  # noqa: E402
from apply_isbi_config_edits import set_scalar  # noqa: E402
from isbi_label_audit import load_brset  # noqa: E402

TASK = "hypertension"
ARM = "recorded"
OUT_BASE = "outputs_isbi_rec"
# (new config name, phase-2 source stem, core run architecture folder)
MODELS = [("convnextv2_recorded", "convnextv2", "convnextv2"),
          ("efficientnet_b2_recorded", "efficientnet_b2", "efficientnet")]
ALLOWED = {"labels_csv", "splits_file", "output_dir"}
SUFFIX = "_brset_recorded"

ERRORS: list[str] = []


def fail_now(msg: str):
    print(f"\nERROR: {msg}\nnothing written.", file=sys.stderr)
    raise SystemExit(2)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for blk in iter(lambda: f.read(1 << 20), b""):
            h.update(blk)
    return h.hexdigest()


def resolve(text: str) -> TrainConfig:
    raw = yaml.safe_load(text) or {}
    raw.update(fold=0, seed=42)
    cfg = TrainConfig.from_dict(raw)
    cfg.validate()
    return cfg


def header(name: str, src: Path, changes: dict[str, str]) -> str:
    changed = ", ".join(f"{k}: {v}" for k, v in changes.items())
    return (
        f"# {name}\n"
        f"#\n"
        f"# GENERATED by scripts/make_recorded_configs.py -- do not edit by hand.\n"
        f"# Source: {src.relative_to(ROOT).as_posix()}\n"
        f"# Arm:    {ARM} (trained and tested on BRSET images with a clinical record)\n"
        f"# Change: {changed}\n"
        f"#\n"
        f"# Identical to the source in every other field, which the generator verifies\n"
        f"# through TrainConfig before writing. Edit the source and regenerate instead.\n"
        f"#\n"
    )


def core_test_ids(fold: int) -> dict[str, set[str]]:
    """Test-set sample ids of the core seed-42 runs of the two source models."""
    out = {}
    for _name, _stem, arch in MODELS:
        p = ROOT / f"outputs_isbi/hypertension_combined/{arch}/fold_{fold}/predictions/val_predictions.csv"
        if not p.exists():
            fail_now(f"core run predictions missing: {p.relative_to(ROOT)} -- needed to pin the test images")
        out[arch] = set(pd.read_csv(p, dtype={"sample_id": str}).sample_id)
    return out


def core_inner_ids(fold: int) -> set[str] | None:
    p = ROOT / f"outputs_isbi/hypertension_combined/{MODELS[0][2]}/fold_{fold}/predictions/inner_val_predictions.csv"
    return set(pd.read_csv(p, dtype={"sample_id": str}).sample_id) if p.exists() else None


def filter_splits(splits: dict, all_ids: set[str], all_pids: set[str], kept: set[str],
                  pid_of: dict[str, str]) -> tuple[dict, list[dict]]:
    if not isinstance(splits, dict) or not isinstance(splits.get("folds"), list):
        fail_now(f"splits JSON: expected an object with a 'folds' list, got keys "
                 f"{list(splits) if isinstance(splits, dict) else type(splits).__name__}")
    folds = splits["folds"]
    if len(folds) != 5:
        fail_now(f"splits JSON: expected 5 folds, found {len(folds)}")
    print(f"  splits top-level keys: {list(splits)}")
    print(f"  fold-0 keys:           {list(folds[0])}")
    if isinstance(splits.get("metadata"), dict):
        print(f"  metadata (kept verbatim): "
              f"{ {k: v for k, v in splits['metadata'].items() if not isinstance(v, (list, dict))} }")

    new_folds, report, test_union = [], [], []
    for i, fd in enumerate(folds):
        if not isinstance(fd, dict):
            fail_now(f"splits JSON: fold entry {i} is {type(fd).__name__}, expected an object")
        fno = fd.get("fold", i)
        if fno != i:
            fail_now(f"splits JSON: entry {i} has fold={fno!r}; expected folds in order 0-4")
        id_keys = []
        for k, v in fd.items():
            if isinstance(v, list) and v and all(isinstance(x, str) for x in v):
                n_img = sum(x in all_ids for x in v)
                n_pid = sum(x in all_pids for x in v)
                if n_img >= 0.99 * len(v):
                    id_keys.append(k)
                elif n_pid >= 0.5 * len(v):
                    fail_now(f"fold {i} key '{k}' holds patient ids, not image ids -- this schema is not "
                             f"handled; paste this output")
                else:
                    fail_now(f"fold {i} key '{k}': only {n_img}/{len(v)} entries are image ids in the CSV")
            elif isinstance(v, list):
                fail_now(f"fold {i} key '{k}' is a list but not of strings (or empty) -- not handled")
        if len(id_keys) < 2:
            fail_now(f"fold {i}: found image-id lists {id_keys}; expected at least train and test")

        # the outer test list is the one that equals the core runs' test predictions
        core = core_test_ids(i)
        ref = core[MODELS[0][2]]
        if any(s != ref for s in core.values()):
            fail_now(f"fold {i}: the two core runs were tested on different images")
        test_keys = [k for k in id_keys if set(fd[k]) & all_ids == ref]
        if len(test_keys) != 1:
            fail_now(f"fold {i}: {len(test_keys)} id lists match the core test predictions "
                     f"({test_keys}); cannot identify the outer test list")
        tk = test_keys[0]
        inner = core_inner_ids(i)
        inner_key = [k for k in id_keys if inner is not None and set(fd[k]) & all_ids == inner]

        nf, updated = {}, []
        for k, v in fd.items():
            nf[k] = [x for x in v if x in kept] if k in id_keys else v
        # an integer that is the length of exactly one id list (e.g. n_train) is a count: update it.
        # Any other field is copied verbatim and listed, so nothing changes silently.
        for k, v in fd.items():
            if k in id_keys or k == "fold":
                continue
            match = [ik for ik in id_keys if isinstance(v, int) and not isinstance(v, bool) and len(fd[ik]) == v]
            if len(match) == 1:
                nf[k] = len(nf[match[0]])
                updated.append(f"{k}:{v}->{nf[k]}")
            elif i == 0:
                print(f"  fold field '{k}' copied verbatim: {v!r}")
        # disjoint lists, patient-grouped test
        for a_ in id_keys:
            for b_ in id_keys:
                if a_ < b_ and set(nf[a_]) & set(nf[b_]):
                    ERRORS.append(f"fold {i}: '{a_}' and '{b_}' share images after filtering")
        test_p = {pid_of[x] for x in nf[tk]}
        other_p = {pid_of[x] for k in id_keys if k != tk for x in nf[k]}
        if test_p & other_p:
            ERRORS.append(f"fold {i}: {len(test_p & other_p)} patients in both test and non-test lists")
        # identical test images to the core runs' record-present BRSET subset
        if set(nf[tk]) != ref & kept:
            ERRORS.append(f"fold {i}: filtered test list != core runs' record-present test images "
                          f"({len(nf[tk])} vs {len(ref & kept)})")
        test_union += nf[tk]
        row = dict(fold=i, test_key=tk, inner_val_key_in_json=(inner_key[0] if inner_key else None),
                   counts_updated=" ".join(updated) or None)
        for k in id_keys:
            row[f"{k}_before"] = len(fd[k])
            row[f"{k}_after"] = len(nf[k])
        row["test_positives"] = None
        report.append(row)
        new_folds.append(nf)

    if len(test_union) != len(set(test_union)):
        ERRORS.append("an image is in more than one test fold")
    if set(test_union) != kept:
        ERRORS.append(f"test folds cover {len(set(test_union))} of {len(kept)} kept images")

    out = {k: v for k, v in splits.items() if k != "folds"}
    out["folds"] = new_folds
    return out, report


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--brset-labels", type=Path, required=True,
                    help="original BRSET labels_brset.csv (sha256 f472398a...)")
    ap.add_argument("--expect-images", type=int, default=7350,
                    help="Adequate BRSET images with a record (label audit); 0 disables the check")
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    os.chdir(ROOT)
    brset_path = args.brset_labels.expanduser().resolve()

    # ---- sources -------------------------------------------------------------
    srcs = {name: ROOT / f"tasks/{TASK}/configs/phase2/{stem}_phase2.yaml" for name, stem, _ in MODELS}
    for name, p in srcs.items():
        if not p.exists():
            fail_now(f"source config missing: {p.relative_to(ROOT)}")
    base = {name: resolve(p.read_text()) for name, p in srcs.items()}
    for name, b in base.items():
        if b.use_weighted_bce:
            fail_now(f"{srcs[name].name} has use_weighted_bce=true -- not the corrected config")
        if not b.labels_csv.endswith("_dedup.csv"):
            fail_now(f"{srcs[name].name} labels_csv is not the dedup CSV ({b.labels_csv})")
    if len({(b.labels_csv, b.splits_file, b.sample_id_col, b.label_col, b.patient_id_col)
            for b in base.values()}) != 1:
        fail_now("the two source configs use different CSV / splits / columns")
    b0 = next(iter(base.values()))
    csv_in, splits_in = ROOT / b0.labels_csv, ROOT / b0.splits_file
    sid, lab, pid = b0.sample_id_col, b0.label_col, b0.patient_id_col
    csv_out = csv_in.with_name(csv_in.stem + SUFFIX + csv_in.suffix)
    splits_out = splits_in.with_name(splits_in.stem + SUFFIX + splits_in.suffix)
    prov_out = splits_in.with_name(splits_in.stem + SUFFIX + ".provenance.json")
    print(f"  labels CSV:  {csv_in.relative_to(ROOT)}  (sha256 {sha256(csv_in)[:12]})")
    print(f"  splits JSON: {splits_in.relative_to(ROOT)}  (sha256 {sha256(splits_in)[:12]})")
    print(f"  BRSET file:  {brset_path}  (sha256 {sha256(brset_path)[:12]})")

    # ---- which rows to keep ----------------------------------------------------
    df = pd.read_csv(csv_in, dtype=str, keep_default_na=False)
    for c in (sid, lab, pid, "source_dataset"):
        if c not in df.columns:
            fail_now(f"{csv_in.name} has no column '{c}' (columns: {list(df.columns)})")
    if df[sid].duplicated().any():
        fail_now(f"{csv_in.name}: duplicated {sid}")
    meta = load_brset(brset_path)
    if not meta.index.is_unique:
        fail_now(f"{brset_path.name}: duplicated image_id among Adequate images")
    is_b = df.source_dataset.str.lower().eq("brset")
    print(f"  CSV rows: {len(df)}  ({int(is_b.sum())} BRSET, "
          f"{sorted(df.source_dataset[~is_b].unique().tolist())} otherwise)")
    b = df[is_b]
    missing = ~b[sid].isin(meta.index)
    if missing.any():
        fail_now(f"{int(missing.sum())} BRSET rows are not Adequate images of {brset_path.name} "
                 f"(e.g. {b[sid][missing].head(3).tolist()})")
    rebuilt = meta.loc[b[sid], "label_rebuilt"].to_numpy()
    if not (b[lab].astype(float).to_numpy() == rebuilt).all():
        fail_now(f"{int((b[lab].astype(float).to_numpy() != rebuilt).sum())} BRSET labels differ from the "
                 f"label rebuilt from {brset_path.name} -- not the source file")
    rec_flag = meta.loc[b[sid], "record"].to_numpy()
    kept_df = b[rec_flag]
    kept = set(kept_df[sid])
    print(f"  kept: {len(kept_df)} BRSET images with a record, {kept_df[pid].nunique()} patients, "
          f"prevalence {kept_df[lab].astype(float).mean():.4f}")
    if len(meta[meta.record]) != len(kept):
        print(f"  note: {len(meta[meta.record]) - len(kept)} Adequate record-present images of the BRSET "
              f"file are not in the dedup CSV")
    if args.expect_images and len(kept) != args.expect_images:
        fail_now(f"kept {len(kept)} images, expected {args.expect_images} (label audit)")
    # patient ids must not change meaning: no kept patient also has dropped images in another fold, by
    # construction (the folds are patient-grouped and we only drop images)

    # ---- splits ----------------------------------------------------------------
    splits = json.loads(splits_in.read_text())
    pid_of = dict(zip(df[sid], df[pid]))
    new_splits, report = filter_splits(splits, set(df[sid]), set(df[pid]), kept, pid_of)
    y_of = dict(zip(kept_df[sid], kept_df[lab].astype(float)))
    for r, fd in zip(report, new_splits["folds"]):
        t = fd[r["test_key"]]
        r["test_positives"] = int(sum(y_of[x] for x in t))
    rep = pd.DataFrame(report)
    print("\n" + rep.to_string(index=False) + "\n")

    # ---- configs ---------------------------------------------------------------
    rel = lambda p: p.relative_to(ROOT).as_posix()  # noqa: E731
    produced: list[tuple[Path, str]] = []
    probes: list[tuple[Path, str]] = []   # same text, data paths pointing at the temp copies
    with tempfile.TemporaryDirectory(dir=ROOT) as tmp:
        tmp = Path(tmp)
        t_csv, t_spl = tmp / csv_out.name, tmp / splits_out.name
        kept_df.to_csv(t_csv, index=False)
        t_spl.write_text(json.dumps(new_splits, indent=2) + "\n")
        # the written CSV must read back to exactly the kept rows
        back = pd.read_csv(t_csv, dtype=str, keep_default_na=False)
        if not back.reset_index(drop=True).equals(kept_df.reset_index(drop=True)):
            ERRORS.append("filtered CSV does not round-trip")

        for name, stem, _arch in MODELS:
            src = srcs[name]
            original = src.read_text()
            changes = {"labels_csv": rel(csv_out), "splits_file": rel(splits_out), "output_dir": OUT_BASE}
            body = re.sub(r"\A(#[^\n]*\n)+", "", original)
            lines = body.splitlines()
            for k, v in changes.items():
                lines, _ = set_scalar(lines, k, v)
            text = header(name, src, changes) + "\n".join(lines) + "\n"
            # resolve against the temp copies (the real files do not exist in a dry run)
            probe = text
            for k, v in (("labels_csv", rel(t_csv)), ("splits_file", rel(t_spl))):
                probe, n = re.subn(rf"(?m)^{k}:.*$", f"{k}: {v}", probe)
                if n != 1:
                    ERRORS.append(f"[{name}] {k} appears {n} times")
            new, old = resolve(probe), base[name]
            diffs = [f.name for f in dataclasses.fields(TrainConfig)
                     if getattr(new, f.name) != getattr(old, f.name)]
            bad = [d for d in diffs if d not in ALLOWED]
            if bad:
                ERRORS.append(f"[{name}] differs from its source in {bad}")
            final = yaml.safe_load(text)
            for k, v in changes.items():
                if final.get(k) != v:
                    ERRORS.append(f"[{name}] {k} did not land (got {final.get(k)!r})")
            if str(new.output_dir) != OUT_BASE:
                ERRORS.append(f"[{name}] output_dir resolves to {new.output_dir!r}")
            dst = ROOT / f"tasks/{TASK}/configs/{ARM}/{name}.yaml"
            produced.append((dst, text))
            probes.append((dst, probe))
            state = ("unchanged" if dst.exists() and dst.read_text() == text
                     else "update" if dst.exists() else "new")
            print(f"  {state:<9} {rel(dst)}")
            d = "".join(difflib.unified_diff(body.splitlines(keepends=True),
                                             re.sub(r"\A(#[^\n]*\n)+", "", text).splitlines(keepends=True),
                                             fromfile=rel(src), tofile=rel(dst), n=0))
            print("".join("      " + ln for ln in d.splitlines(keepends=True)))

        # ---- run_dir uniqueness across every config in the tree ---------------
        owners: dict[str, list[str]] = {}
        pool = [(p, p.read_text()) for p in sorted(ROOT.glob("tasks/*/configs/phase2/*.yaml"))]
        pool += [(p, p.read_text()) for p in sorted(ROOT.glob("tasks/*/configs/vessel/*.yaml"))
                 if "multimodal" not in p.name]
        pool += [(p, p.read_text()) for sub in ("resolution", "wbce")
                 for p in sorted(ROOT.glob(f"tasks/*/configs/{sub}/*.yaml"))]
        pool += probes
        for p, text in pool:
            try:
                rd = str(resolve(text).run_dir)
            except Exception as exc:  # noqa: BLE001
                ERRORS.append(f"[{p.name}] does not resolve: {exc}")
                continue
            owners.setdefault(rd, []).append(rel(p))
        for rd, who in owners.items():
            if len(who) > 1:
                ERRORS.append(f"run_dir collision {rd}: {who}")
        print(f"\n  {len(owners)} distinct run_dirs across {len(pool)} configs")

        for e in ERRORS:
            print(f"  ERROR  {e}")
        if ERRORS:
            print(f"\n{len(ERRORS)} errors -- nothing written.")
            return 1
        if not args.write:
            print(f"\nverified: {len(kept)} images, 5 folds, {len(produced)} configs. "
                  f"Dry run -- rerun with --write.")
            return 0

        for dst in (csv_out, splits_out):
            if dst.exists() and sha256(dst) != sha256(tmp / dst.name):
                fail_now(f"{rel(dst)} exists with different content -- move it aside first")
        shutil.copyfile(t_csv, csv_out)
        shutil.copyfile(t_spl, splits_out)
    for (dst, text), (name, _stem, _arch) in zip(produced, MODELS):
        # now that the data files exist, the real config must resolve too
        if str(resolve(text).run_dir) == "" or not str(resolve(text).labels_csv).endswith(csv_out.name):
            fail_now(f"[{name}] final config does not resolve to the written CSV")
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text)
    prov = dict(
        generator="scripts/make_recorded_configs.py",
        inputs={rel(csv_in): sha256(csv_in), rel(splits_in): sha256(splits_in), str(brset_path): sha256(brset_path)},
        outputs={rel(csv_out): sha256(csv_out), rel(splits_out): sha256(splits_out),
                 **{rel(d): sha256(d) for d, _ in produced}},
        rule="source_dataset == brset AND quality == Adequate AND comorbidities not empty",
        images=len(kept), patients=int(kept_df[pid].nunique()),
        prevalence=float(kept_df[lab].astype(float).mean()),
        folds=report,
    )
    prov_out.write_text(json.dumps(prov, indent=2) + "\n")
    print(f"\nwritten:\n  {rel(csv_out)}\n  {rel(splits_out)}\n  {rel(prov_out)}")
    for d, _ in produced:
        print(f"  {rel(d)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
